	`submitter_email` text NOT NULL,
	`submitter_name` text,
	`trace_filename` text NOT NULL,
	`metadata_filename` text,
	`trace_storage_key` text NOT NULL,
	`metadata_storage_key` text,
	`trace_bytes` integer NOT NULL,
