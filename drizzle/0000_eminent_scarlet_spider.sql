	`public_consent` integer DEFAULT false NOT NULL,
	`review_note` text,
	`reviewed_at` text,
	`reviewed_by` text,
	`run_id` text,
	`model` text,
	`model_family` text,
	`method` text,
	`gpu_type` text,
	`gpu_count` text,
